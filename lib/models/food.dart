class Food {
  final int id;
  final String name;
  final String category;
  final String restaurant;
  final String emoji;
  final int price;
  final double rating;
  final String description;

  const Food({
    required this.id,
    required this.name,
    required this.category,
    required this.restaurant,
    required this.emoji,
    required this.price,
    required this.rating,
    required this.description,
  });
}
